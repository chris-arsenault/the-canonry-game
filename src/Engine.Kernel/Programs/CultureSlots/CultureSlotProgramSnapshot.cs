namespace Engine.Kernel;

internal static class CultureSlotProgramSnapshot
{
    public static void Write(global::System.IO.BinaryWriter writer, CultureSlotProgramRuntime program)
    {
        KernelProgramSnapshot.WriteData(writer, program.Data);
        KernelProgramSnapshot.WriteState(writer, program.State);
    }

    public static void Read(global::System.IO.BinaryReader reader, CultureSlotProgramRuntime program)
    {
        KernelProgramSnapshot.ReadData(reader, program.Data);
        KernelProgramSnapshot.ReadState(reader, program.State);
    }
}
